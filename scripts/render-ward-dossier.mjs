#!/usr/bin/env node
/**
 * Render PKM ward investment dossier (Markdown + .data.json) from MLIT cache/API.
 *
 * Usage:
 *   node scripts/render-ward-dossier.mjs --ward 北区
 *   node scripts/render-ward-dossier.mjs --episode ep07
 */
import { readFile, writeFile, mkdir, access } from "node:fs/promises";
import path from "node:path";
import {
  collectPrice,
  collectStation,
  collectLandPrice,
  collectPopulation,
  collectDisaster,
  EPISODE_WARDS,
  loadEnv,
} from "./mlit-collector.mjs";

const root = process.cwd();
const PKM_ROOT =
  process.env.PKM_ROOT ||
  path.join(process.env.HOME || "", ".gemini/antigravity/scratch/projects/GSF-PKM");
const DOSSIER_DIR = path.join(PKM_ROOT, "PKM/30 Resources/RealEstate/Tokyo/wards");
const BENCHMARKS = path.join(root, "docs/verification/tokyo-ward-series-benchmarks.json");
const INCOME_CARD = "PKM/30 Resources/도쿄_23구_인당_실질소득_통계_2025.md";

function parseArgs(argv) {
  const out = { ward: "", episode: "", year: 2025, noCache: false };
  for (let i = 2; i < argv.length; i += 1) {
    const a = argv[i];
    if (a === "--ward") out.ward = argv[++i] ?? "";
    else if (a === "--episode") out.episode = (argv[++i] ?? "").toLowerCase();
    else if (a === "--year") out.year = parseInt(argv[++i] ?? "2025", 10);
    else if (a === "--no-cache") out.noCache = true;
  }
  return out;
}

function grossYieldProxy(rent1rMan, est70Man) {
  if (!rent1rMan || !est70Man) return null;
  const annualRent = rent1rMan * 12;
  return Math.round((annualRent / est70Man) * 1000) / 10;
}

function disasterLines(detail) {
  return Object.entries(detail ?? {}).map(([k, v]) => {
    const flag = v?.has_risk ? "⚠️" : "✅";
    return `- ${flag} **${k}**: ${v?.label ?? k} (${v?.feature_count ?? 0} features in tile sample)`;
  });
}

async function buildDossier(ward, benchmarks, year, noCache) {
  const price = await collectPrice(ward, year, null, noCache);
  const station = await collectStation(ward, noCache);
  const land = await collectLandPrice(ward, year, noCache);
  const pop = await collectPopulation(ward, noCache);
  const disaster = await collectDisaster(ward, noCache);

  const suumo = benchmarks.suumo_rent_new_build_station_5min?.wards?.[ward];
  const income = benchmarks.income_density_per_capita?.wards?.[ward];
  const yield1r = grossYieldProxy(suumo?.["1R"], price.est_70sqm);

  const data = {
    ward,
    generated_at: new Date().toISOString().slice(0, 10),
    price,
    station,
    land,
    population: pop,
    disaster,
    suumo,
    income,
    yield_proxy_1r_pct: yield1r,
    sources: {
      mlit: "https://www.reinfolib.mlit.go.jp/",
      income_card: INCOME_CARD,
    },
  };

  const topDistricts = (price.districts ?? []).slice(0, 5);
  const topStations = (station.stations ?? []).slice(0, 5);

  const md = `# ${ward} — 투자·거주 참조 Dossier

> MLIT API + benchmarks SSOT 자동 생성. 타일·메시 집계는 행정구 경계와 **완전 일치하지 않을 수 있음**.

## 요약 (Joseph 편집)

- 성약가 70㎡ 환산: **${price.est_70sqm ?? "—"}万円** (${price.count ?? 0}건, ${price.fetched_at ?? ""})
- 최다 승하차 역: **${station.top_station?.name ?? "—"}** (${station.top_station?.passengers_daily?.toLocaleString() ?? "—"}명/일, 타일 샘플)
- 인구 2020→2040: **${pop.change_rate_2020_2040 ?? "—"}** (메시 합산 근사)
- 표면 gross yield (1R/SUUMO÷70㎡매매): **${yield1r != null ? `${yield1r}%` : "SUUMO 미수집"}** — 세전 proxy, C-tier 주석 권장

## 가격 (XIT001)

| 항목 | 값 |
|------|-----|
| ㎡당 평균 | ${price.ward_avg_sqm ?? "—"} 万円/㎡ |
| 70㎡ 환산 | ${price.est_70sqm ?? "—"} 万円 |
| 거래 건수 | ${price.count ?? 0} |

### 町名별 ㎡단가 (상위)

${topDistricts.map(d => `- **${d.name}**: ${d.avg_sqm}万/㎡ (${d.count}건)`).join("\n")}

## 임대·수익률 proxy

${suumo
  ? `| 타입 | 임대(万円) |\n|------|----------|\n${Object.entries(suumo)
      .filter(([k]) => /^\d|R|LDK|K/.test(k))
      .map(([k, v]) => `| ${k} | ${v} |`)
      .join("\n")}`
  : "_SUUMO 스냅샷 미등록 — `fetch-suumo-snapshot.mjs` 실행_"}

## 유동성 (XKT015)

| 역 | 승하차/일 | 노선 |
|----|-----------|------|
${topStations.map(s => `| ${s.name} | ${s.passengers_daily.toLocaleString()} | ${s.line} |`).join("\n")}

## 수요 전망 (XKT013)

| 연도 | 인구(메시 합) |
|------|---------------|
${Object.entries(pop.population_by_year ?? {})
  .map(([y, n]) => `| ${y} | ${Number(n).toLocaleString()} |`)
  .join("\n")}

변화율 2020→2040: **${pop.change_rate_2020_2040 ?? "—"}**

## 물리 리스크 (XKT025~029)

${disasterLines(disaster.detail).join("\n")}

## 소득·세무

- 인당 실질소득 밀도: ${income ? `**${income.value}万円/人** (23구 ${income.rank}위)` : "_PKM income card 미등록_"}
- 카드: \`${INCOME_CARD}\`

## 미확인·다음 액션

- [ ] 교통시간(都心) — C-tier, 乗換案내 확인
- [ ] SUUMO 임대 스냅샷 B-layer 커밋
- [ ] Joseph: 투자 thesis 3줄 편집

---
*Generated by \`scripts/render-ward-dossier.mjs\` · ${data.generated_at}*
`;

  return { md, data };
}

async function main() {
  await loadEnv();
  const args = parseArgs(process.argv);
  let wards = [];
  if (args.ward) wards = [args.ward];
  else if (args.episode) {
    wards = EPISODE_WARDS[args.episode];
    if (!wards) {
      console.error(`Unknown episode: ${args.episode}`);
      process.exit(1);
    }
  } else {
    console.error("Usage: render-ward-dossier.mjs --ward <区> | --episode ep07");
    process.exit(2);
  }

  let benchmarks = {};
  try {
    benchmarks = JSON.parse(await readFile(BENCHMARKS, "utf8"));
  } catch {
    /* optional */
  }

  await mkdir(DOSSIER_DIR, { recursive: true });
  const written = [];

  for (const ward of wards) {
    const { md, data } = await buildDossier(ward, benchmarks, args.year, args.noCache);
    const mdPath = path.join(DOSSIER_DIR, `${ward}.md`);
    const jsonPath = path.join(DOSSIER_DIR, `${ward}.data.json`);
    await writeFile(mdPath, md);
    await writeFile(jsonPath, `${JSON.stringify(data, null, 2)}\n`);
    written.push({ md: mdPath, json: jsonPath });
  }

  console.log(JSON.stringify({ ok: true, written }, null, 2));
}

main().catch(err => {
  console.error(err);
  process.exit(2);
});
